import { TAU } from '../../core/utils.js';
import { rr, eyePair } from './kit.js';

/* --- ДЕЦИЗИЯ 1986: дерево решений в горшке, таблички ✓/✗ на ветках --- */
export function treeArt(g, wp, mv, t, ay) {
  const sway = mv ? Math.sin(wp) * 0.08 : Math.sin(t * 1.7) * 0.04;
  /* горшок */
  g.fillStyle = '#b0603c';
  g.beginPath();
  g.moveTo(-5.2, 5.4);
  g.lineTo(5.2, 5.4);
  g.lineTo(3.9, 10.6);
  g.lineTo(-3.9, 10.6);
  g.closePath();
  g.fill();
  g.fillStyle = '#c97550';
  g.fillRect(-6, 3.7, 12, 2.1);
  g.fillStyle = 'rgba(0,0,0,.2)';
  g.fillRect(-4, 8.5, 8, 1.5);
  /* ствол + ветки + листва */
  g.save();
  g.rotate(sway);
  g.fillStyle = '#8a5a34';
  g.beginPath();
  g.moveTo(-1.7, 4.2);
  g.quadraticCurveTo(-1.3, -0.8, 2.4, -5.6);
  g.lineTo(4.3, -4.6);
  g.quadraticCurveTo(1.6, -0.5, 2.1, 4.2);
  g.closePath();
  g.fill();
  g.strokeStyle = '#8a5a34';
  g.lineWidth = 2.1;
  g.lineCap = 'round';
  g.beginPath();
  g.moveTo(1.4, -3.6);
  g.lineTo(-3.8, -8.8);
  g.stroke();
  g.beginPath();
  g.moveTo(2.2, -4);
  g.lineTo(7.4, -9.4);
  g.stroke();
  g.beginPath();
  g.moveTo(1.9, -4.6);
  g.lineTo(1.2, -11);
  g.stroke();
  g.fillStyle = '#2f7d4f';
  g.beginPath();
  g.arc(-4.8, -10.2, 3.6, 0, TAU);
  g.fill();
  g.beginPath();
  g.arc(1.3, -12.6, 4.4, 0, TAU);
  g.fill();
  g.beginPath();
  g.arc(7.6, -10.8, 3.2, 0, TAU);
  g.fill();
  g.fillStyle = '#3f9d63';
  g.beginPath();
  g.arc(-0.2, -11.2, 3, 0, TAU);
  g.fill();
  g.beginPath();
  g.arc(5.2, -12, 2.4, 0, TAU);
  g.fill();
  /* таблички ✓/✗ на ветках */
  const sw = Math.sin(t * 2.4) * 0.5;
  g.save();
  g.translate(-4.8, -7.4);
  g.rotate(sw * 0.5);
  g.strokeStyle = 'rgba(255,255,255,.35)';
  g.lineWidth = 0.6;
  g.beginPath();
  g.moveTo(0, 0);
  g.lineTo(0, 1.3);
  g.stroke();
  g.fillStyle = '#2f7d4f';
  g.beginPath();
  rr(g, -2.2, 1.3, 4.4, 3.2, 0.9);
  g.fill();
  g.strokeStyle = '#eafff2';
  g.lineWidth = 1;
  g.beginPath();
  g.moveTo(-1.2, 2.9);
  g.lineTo(-0.4, 3.8);
  g.lineTo(1.2, 1.9);
  g.stroke();
  g.restore();
  g.save();
  g.translate(7.4, -7.8);
  g.rotate(-sw * 0.5);
  g.strokeStyle = 'rgba(255,255,255,.35)';
  g.lineWidth = 0.6;
  g.beginPath();
  g.moveTo(0, 0);
  g.lineTo(0, 1.3);
  g.stroke();
  g.fillStyle = '#8b3a3a';
  g.beginPath();
  rr(g, -2.2, 1.3, 4.4, 3.2, 0.9);
  g.fill();
  g.strokeStyle = '#ffe9e9';
  g.lineWidth = 1;
  g.beginPath();
  g.moveTo(-1.2, 1.9);
  g.lineTo(1.2, 3.9);
  g.moveTo(1.2, 1.9);
  g.lineTo(-1.2, 3.9);
  g.stroke();
  g.restore();
  g.restore();
  /* лицо на стволе */
  eyePair(g, -0.1, 2.5, 0.7, ay, t, '#bff7d2', '#123c26');
  g.strokeStyle = '#123c26';
  g.lineWidth = 0.9;
  g.beginPath();
  g.arc(1.2, 2.9, 1.3, Math.PI * 0.1, Math.PI * 0.9);
  g.stroke();
}
